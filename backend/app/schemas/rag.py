from __future__ import annotations

from datetime import datetime
from uuid import UUID
from typing import Any, Literal
from pydantic import Field, field_validator, model_validator
from app.schemas.base import BaseSchema, ORMBaseSchema


class SourceDocumentCreate(BaseSchema):
    """
    Schema for saving uploaded, manual, or web source documents.
    """
    book_id: UUID | None = None
    title: str = Field(..., min_length=2, max_length=500)
    source_type: str = Field(..., min_length=2, max_length=100)
    source_url: str | None = Field(None, max_length=2000)
    raw_text: str | None = None
    document_metadata: dict | None = None
    status: str = Field("created", max_length=50)

    @field_validator("title", "source_type", mode="before")
    @classmethod
    def strip_whitespace(cls, v: Any) -> Any:
        if isinstance(v, str):
            return v.strip()
        return v


class SourceDocumentUpdate(BaseSchema):
    """
    Schema for updating source document metadata or status.
    """
    title: str | None = Field(None, min_length=2, max_length=500)
    source_type: str | None = Field(None, min_length=2, max_length=100)
    source_url: str | None = Field(None, max_length=2000)
    raw_text: str | None = None
    document_metadata: dict | None = None
    status: str | None = Field(None, max_length=50)

    @field_validator("title", "source_type", mode="before")
    @classmethod
    def strip_whitespace(cls, v: Any) -> Any:
        if isinstance(v, str):
            return v.strip()
        return v


class SourceDocumentResponse(ORMBaseSchema):
    """
    Response schema returning complete details of a source document.
    """
    book_id: UUID | None
    title: str
    source_type: str
    source_url: str | None
    raw_text: str | None
    document_metadata: dict | None
    status: str


class SourceDocumentListItem(BaseSchema):
    """
    Lightweight summary schema for listing source documents.
    """
    id: UUID
    book_id: UUID | None
    title: str
    source_type: str
    source_url: str | None
    status: str
    created_at: datetime | None
