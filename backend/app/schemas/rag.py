class ChunkingRequest(BaseSchema):
    """
    Request schema to trigger text chunking.
    """
    document_id: UUID
    chunk_size: int = Field(1000, ge=200, le=5000)
    chunk_overlap: int = Field(150, ge=0, le=1000)
    strategy: Literal["recursive", "paragraph", "sentence", "fixed"] = "recursive"

    @model_validator(mode="after")
    def validate_overlap(self) -> ChunkingRequest:
        if self.chunk_overlap >= self.chunk_size:
            raise ValueError("chunk_overlap must be less than chunk_size")
        return self


class ChunkingResponse(BaseSchema):
    """
    Response detailing text chunking execution results.
    """
    document_id: UUID
    chunks_created: int = Field(..., ge=0)
    strategy: str
    chunk_size: int
    chunk_overlap: int
    status: str
    message: str | None = None


class RetrievalRequest(BaseSchema):
    """
    Input schema to query the RAG retriever.
    """
    book_id: UUID | None = None
    query: str = Field(..., min_length=2, max_length=1000)
    top_k: int = Field(8, ge=1, le=20)
    include_raw_text: bool = True
    filters: dict | None = None

    @field_validator("query", mode="before")
    @classmethod
    def strip_whitespace(cls, v: Any) -> Any:
        if isinstance(v, str):
            return v.strip()
        return v


class RetrievalResultItem(BaseSchema):
    """
    Represents a single retrieved text chunk candidate.
    """
    chunk_id: UUID
    document_id: UUID
    book_id: UUID | None
    chunk_text: str | None = None
    score: float | None = Field(None, ge=0.0)
    source_title: str | None = None
    source_url: str | None = None
    metadata: dict | None = None


class RetrievalResponse(BaseSchema):
    """
    Response schema returning list of retrieval matches.
    """
    query: str
    top_k: int = Field(..., ge=1)
    results: list[RetrievalResultItem]
    total_results: int = Field(..., ge=0)
    status: str
    message: str | None = None
